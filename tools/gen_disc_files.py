#!/usr/bin/env python3
"""Writes the table of retail game files that setup checks a user's disc image against
(src/setup/disc_files_<ID>.inc; docs/SETUP.md "Disc image check").

    python tools/gen_disc_files.py orig/GLME01.iso orig/GLMP01.iso

Each entry is a file of the disc's file system: path, size and CRC-32 (zlib) of its contents
(no game data is stored, only these checksums). The input must be a clean dump (verify it
against redump first, e.g. Dolphin: Properties > Verify).
"""
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def files(iso: Path):
    with open(iso, "rb") as f:
        game_id = f.read(6).decode("ascii")
        f.seek(0x424)
        fst_off, fst_size = struct.unpack(">II", f.read(8))
        f.seek(fst_off)
        fst = f.read(fst_size)
        count = struct.unpack_from(">I", fst, 8)[0]
        strings = 12 * count

        def name(i):
            o = strings + (struct.unpack_from(">I", fst, 12 * i)[0] & 0xFFFFFF)
            return fst[o:fst.index(b"\0", o)].decode("shift_jis")

        stack, out = [(count, "/")], []
        for i in range(1, count):
            while len(stack) > 1 and i >= stack[-1][0]:
                stack.pop()
            w, a, b = struct.unpack_from(">III", fst, 12 * i)
            p = stack[-1][1] + name(i)
            if w >> 24:
                stack.append((b, p + "/"))
            else:
                out.append((p, a, b))
        rows = []
        for p, a, b in out:
            f.seek(a)
            rows.append((p, b, zlib.crc32(f.read(b))))
        return game_id, rows


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 1
    for iso in sys.argv[1:]:
        game_id, rows = files(Path(iso))
        dst = ROOT / "src" / "setup" / f"disc_files_{game_id}.inc"
        with open(dst, "w", encoding="utf-8", newline="\n") as o:
            o.write(f"// Generated by tools/gen_disc_files.py from a clean {game_id} dump: path, size, CRC-32.\n")
            for p, size, h in rows:
                esc = p.replace("\\", "\\\\").replace('"', '\\"')
                o.write(f'{{"{esc}", {size:#x}u, {h:#010x}u}},\n')
        print(f"{dst}: {len(rows)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
